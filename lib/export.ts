import { Scorecard } from '@/types/scenario';

export function exportScorecardAsJson(scorecard: Scorecard): void {
  const dataStr =
    'data:text/json;charset=utf-8,' +
    encodeURIComponent(JSON.stringify(scorecard, null, 2));
  const downloadAnchor = document.createElement('a');
  downloadAnchor.setAttribute('href', dataStr);
  downloadAnchor.setAttribute(
    'download',
    `truthfence-audit-${scorecard.id}-${new Date().toISOString().slice(0, 10)}.json`
  );
  document.body.appendChild(downloadAnchor);
  downloadAnchor.click();
  downloadAnchor.remove();
}

export function generateMarkdownReport(scorecard: Scorecard): string {
  const lines: string[] = [];
  lines.push(`# TruthFence AI — Adversarial Reliability Audit Report`);
  lines.push(`**Product Tagline:** "Don't trust the response. Test the evidence."\n`);
  lines.push(`- **Audit Run ID:** \`${scorecard.id}\``);
  lines.push(`- **Timestamp:** ${scorecard.timestamp}`);
  lines.push(`- **Evaluated Model:** \`${scorecard.model}\` via Gemini API`);
  lines.push(`- **Overall Pass Rate:** **${scorecard.passRate}%** (${scorecard.passedCount}/${scorecard.totalScenarios} passed)\n`);

  lines.push(`## 1. Executive Scorecard`);
  lines.push(`| Metric | Value | Status |`);
  lines.push(`|---|---|---|`);
  lines.push(`| **Total Scenarios** | ${scorecard.totalScenarios} | Complete |`);
  lines.push(`| **Deterministic Checks** | ${scorecard.deterministicPassed} / ${scorecard.deterministicTotal} | ${scorecard.deterministicPassed === scorecard.deterministicTotal ? 'PASS' : 'FLAGGED'} |`);
  lines.push(`| **Heuristic Checks** | ${scorecard.heuristicPassed} / ${scorecard.heuristicTotal} | ${scorecard.heuristicPassed === scorecard.heuristicTotal ? 'PASS' : 'FLAGGED'} |`);
  lines.push(`| **Errors / Failures** | ${scorecard.failedCount} | ${scorecard.failedCount === 0 ? 'CLEAN' : 'ATTENTION REQUIRED'} |\n`);

  lines.push(`## 2. Detailed Scenario Results`);
  for (const r of scorecard.results) {
    const statusMark = r.evaluatorResult.passed ? '✅ PASS' : '❌ FAIL';
    lines.push(`### ${r.scenario.title} — ${statusMark}`);
    lines.push(`- **Category:** \`${r.scenario.category}\` ${r.evaluatorResult.isHeuristic ? '*(Heuristic)*' : '*(Deterministic)*'}`);
    lines.push(`- **Metric:** ${r.evaluatorResult.metricName}: \`${r.evaluatorResult.metricValue}\` (Threshold: \`${r.evaluatorResult.threshold || 'N/A'}\`)`);
    lines.push(`- **Evaluation Rationale:** ${r.evaluatorResult.reason}`);
    lines.push(`- **Inference Latency:** ${r.latencyMs}ms`);

    if (r.evaluatorResult.details.matchedQuotations?.length) {
      lines.push(`- **Verified Exact Quotes:**`);
      for (const q of r.evaluatorResult.details.matchedQuotations) {
        lines.push(`  - > "${q}"`);
      }
    }

    if (r.evaluatorResult.details.unverifiedClaims?.length) {
      lines.push(`- **Unverified / Fabricated Passages:**`);
      for (const u of r.evaluatorResult.details.unverifiedClaims) {
        lines.push(`  - > "${u}"`);
      }
    }

    lines.push(`\n**Raw Model Output:**`);
    lines.push('```text');
    lines.push(r.rawOutput || (r.error ? `ERROR: ${r.error}` : 'No output'));
    lines.push('```\n');
  }

  lines.push(`---\n*Generated by TruthFence AI — Open-Source AI Reliability Workbench*`);
  return lines.join('\n');
}

export function exportScorecardAsMarkdown(scorecard: Scorecard): void {
  const md = generateMarkdownReport(scorecard);
  const dataStr =
    'data:text/markdown;charset=utf-8,' + encodeURIComponent(md);
  const downloadAnchor = document.createElement('a');
  downloadAnchor.setAttribute('href', dataStr);
  downloadAnchor.setAttribute(
    'download',
    `truthfence-audit-${scorecard.id}-${new Date().toISOString().slice(0, 10)}.md`
  );
  document.body.appendChild(downloadAnchor);
  downloadAnchor.click();
  downloadAnchor.remove();
}
